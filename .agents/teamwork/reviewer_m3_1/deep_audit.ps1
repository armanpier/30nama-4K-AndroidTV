# Deep-dive Parity and Scraps Audit Script
$ErrorActionPreference = "Stop"

$repo1 = "c:\Users\Arman\Documents\antigravity\quirky-turing\android"
$repo2 = "C:\Users\Arman\Documents\antigravity\AsanVPN\android"

Write-Host "=== 1. Complete File Listing (Sorted) ==="
$ephemeralRegex = '\\(\.gradle|build|\.idea|captures|\.kotlin)\\'
$files1 = Get-ChildItem -Recurse -Force -File $repo1 | Where-Object { $_.FullName -notmatch $ephemeralRegex }
$files2 = Get-ChildItem -Recurse -Force -File $repo2 | Where-Object { $_.FullName -notmatch $ephemeralRegex }

Write-Host "Count in Repo 1: $($files1.Count)"
Write-Host "Count in Repo 2: $($files2.Count)"

$list1 = $files1 | ForEach-Object {
    $rel = $_.FullName.Substring($repo1.Length).TrimStart('\', '/')
    [PSCustomObject]@{
        RelativePath = $rel
        Length = $_.Length
        SHA256 = (Get-FileHash -Algorithm SHA256 -Path $_.FullName).Hash
    }
} | Sort-Object RelativePath

$list2 = $files2 | ForEach-Object {
    $rel = $_.FullName.Substring($repo2.Length).TrimStart('\', '/')
    [PSCustomObject]@{
        RelativePath = $rel
        Length = $_.Length
        SHA256 = (Get-FileHash -Algorithm SHA256 -Path $_.FullName).Hash
    }
} | Sort-Object RelativePath

Write-Host "`nAll 80 files with SHA-256 and Size:"
for ($i = 0; $i -lt $list1.Count; $i++) {
    $item1 = $list1[$i]
    $item2 = $list2[$i]
    $matchPath = ($item1.RelativePath -eq $item2.RelativePath)
    $matchHash = ($item1.SHA256 -eq $item2.SHA256)
    $matchLen = ($item1.Length -eq $item2.Length)
    if (-not ($matchPath -and $matchHash -and $matchLen)) {
        Write-Host "MISMATCH at index $i : PathMatch=$matchPath, HashMatch=$matchHash, LenMatch=$matchLen"
        Write-Host "  Repo1: $($item1.RelativePath) ($($item1.Length) bytes) $($item1.SHA256)"
        Write-Host "  Repo2: $($item2.RelativePath) ($($item2.Length) bytes) $($item2.SHA256)"
    } else {
        Write-Host "OK [$i]: $($item1.RelativePath) ($($item1.Length) B) -> $($item1.SHA256)"
    }
}

Write-Host "`n=== 2. Check .gitignore files ==="
$gitIgnore1 = Get-Content -Raw "$repo1\.gitignore"
$gitIgnore2 = Get-Content -Raw "$repo2\.gitignore"
Write-Host ".gitignore match: $($gitIgnore1 -eq $gitIgnore2)"
Write-Host "Content of .gitignore:"
Write-Host $gitIgnore1

Write-Host "`n=== 3. Check .kotlin directory in both repos ==="
$kotlinItems1 = Get-ChildItem -Recurse -Force "$repo1\.kotlin" -ErrorAction SilentlyContinue
$kotlinItems2 = Get-ChildItem -Recurse -Force "$repo2\.kotlin" -ErrorAction SilentlyContinue

Write-Host "Repo 1 .kotlin items count: $($kotlinItems1.Count)"
foreach ($k in $kotlinItems1) {
    Write-Host "  $($k.FullName) (Length: $($k.Length), IsDir: $($k.PSIsContainer))"
}
Write-Host "Repo 2 .kotlin items count: $($kotlinItems2.Count)"
foreach ($k in $kotlinItems2) {
    Write-Host "  $($k.FullName) (Length: $($k.Length), IsDir: $($k.PSIsContainer))"
}

Write-Host "`n=== 4. Check ui_backup_original_dark ==="
$uiBackup1 = Get-ChildItem -Recurse -Force "$repo1\ui_backup_original_dark"
$uiBackup2 = Get-ChildItem -Recurse -Force "$repo2\ui_backup_original_dark"
Write-Host "Repo 1 ui_backup files: $($uiBackup1.Count)"
Write-Host "Repo 2 ui_backup files: $($uiBackup2.Count)"

Write-Host "`n=== 5. Check Git Status (if git repositories) ==="
if (Test-Path "$repo1\..\.git") {
    Write-Host "Repo 1 parent git status for android:"
    git -C "$repo1\.." status --porcelain android
} else {
    Write-Host "Repo 1 is not in a git repo"
}

if (Test-Path "$repo2\..\.git") {
    Write-Host "Repo 2 parent git status for android:"
    git -C "$repo2\.." status --porcelain android
} elseif (Test-Path "$repo2\.git") {
    Write-Host "Repo 2 git status:"
    git -C "$repo2" status --porcelain
} else {
    Write-Host "Repo 2 is not in a git repo"
}

Write-Host "`n=== 6. Check APKs Generated by Build ==="
$apks1 = Get-ChildItem -Recurse -Force "$repo1\app\build\outputs\apk" -Filter "*.apk" -ErrorAction SilentlyContinue
$apks2 = Get-ChildItem -Recurse -Force "$repo2\app\build\outputs\apk" -Filter "*.apk" -ErrorAction SilentlyContinue

Write-Host "Repo 1 APKs:"
foreach ($a in $apks1) {
    Write-Host "  $($a.FullName) ($($a.Length) bytes)"
}
Write-Host "Repo 2 APKs:"
foreach ($a in $apks2) {
    Write-Host "  $($a.FullName) ($($a.Length) bytes)"
}
